// Package stringx 提供一组面向生产项目的字符串处理工具。
//
// 该包在 Go 标准库 strings、unicode、regexp、net 等基础能力之上，补充了以下常见场景：
//
//   - 命名风格转换，如驼峰、下划线和短横线格式互转。
//   - 字符串判空、首字符大小写处理、按字符或字节安全截取。
//   - 空白规范化、文本长度、显示宽度、单词统计和单词切分。
//   - 字符映射、删除、压缩重复字符和左右居中填充。
//   - 严格的邮箱、URL、主机名、IP、UUID 等协议型校验。
//   - 中国身份证、统一社会信用代码、银行卡等常见业务编号校验。
//   - 返回 error 的严格验证 API，便于上层业务输出明确失败原因。
//   - 按功能拆分的子包，包括 caseconv、textx、validatex、randomx、inflectx、maskx、unsafex。
//   - 英文单复数转换、常见格式校验和随机字符串生成。
//   - 零拷贝字符串与字节切片转换。
//
// 更细分的严格校验、解析和脱敏能力可通过各子包按需引入，
// 例如 validatex 提供国际化域名、业务编号和解析型能力。
